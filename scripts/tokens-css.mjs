/**
 * Writes src/design/tokens.css from src/design/tokens.json.
 *
 * The JSON is the one place a token is decided. Two things read it: this
 * script, so that stylesheets have custom properties to use, and
 * src/design/tokens.ts, so that the code that paints a highlight has the pen
 * colours. Neither holds a value of its own.
 *
 *   npm run tokens
 *
 * tests/designTokens.test.ts runs the same function and fails if the file on
 * disk is not what it produces, so a forgotten run is caught rather than
 * shipped.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

// Resolved against the repository root, which is where npm scripts and vitest
// both run from. Not from import.meta.url: vitest rewrites that to an http
// URL, and the test here reads the same two files this script writes.
const SOURCE = resolve(process.cwd(), 'src/design/tokens.json');
const OUTPUT = resolve(process.cwd(), 'src/design/tokens.css');

/** Wraps a note into a CSS comment, keeping the blank lines that paragraph it. */
function comment(lines, indent = '') {
  const body = lines.map((line) => (line ? `${indent}   ${line}` : ''));
  return [`${indent}/* ${body[0].trim()}`, ...body.slice(1), `${indent}*/`].join('\n');
}

/**
 * The dark overrides, written twice.
 *
 * `[data-theme='dark']` is somebody choosing it, and the media query is
 * somebody leaving it on Match the system, which is why that one has to
 * exclude anybody who chose Light: without `:not([data-theme='light'])` a
 * light choice would be overruled by the operating system every evening.
 *
 * Against `:root` only. The main block also carries `:host` and
 * `.kona-tokens`, which are the panel inside the page, and 17 settled that the
 * panel is a dark slab over any page rather than a thing that follows a
 * preference.
 */
function darkBlocks(prefix, dark, note) {
  const lines = [
    // The half we do not paint: the scrollbar, the caret, and anything native
    // a form draws. Only in the dark blocks, because a document with no
    // color-scheme is already light, and saying so on the main block would
    // reach `.kona-tokens` as well, which is the panel's shadow root.
    '  color-scheme: dark;',
    ...Object.entries(dark).map(([name, value]) => `  --${prefix}-${name}: ${value};`),
  ];
  return [
    '',
    comment(note),
    "@media (prefers-color-scheme: dark) {",
    "  :root:not([data-theme='light']) {",
    ...lines.map((line) => `  ${line}`),
    '  }',
    '}',
    '',
    "[data-theme='dark'] {",
    ...lines,
    '}',
  ].join('\n');
}

export function render(tokens) {
  const { prefix, note, selector, selectorNote, groups, dark, darkNote } = tokens;
  const out = [
    '/* Generated by scripts/tokens-css.mjs from tokens.json. Do not edit. */',
    comment(note),
    '',
    comment(selectorNote),
    `${selector} {`,
  ];
  for (const group of groups) {
    out.push(comment(group.note, '  '));
    for (const [name, value] of Object.entries(group.vars)) {
      out.push(`  --${prefix}-${name}: ${value};`);
    }
    out.push('');
  }
  // The last group leaves a blank line behind it; the brace closes on its own.
  out[out.length - 1] = '}';
  if (dark) out.push(darkBlocks(prefix, dark, darkNote ?? []));
  return `${out.join('\n')}\n`;
}

export function read() {
  return JSON.parse(readFileSync(SOURCE, 'utf8'));
}

if (import.meta.url === `file://${process.argv[1]?.replace(/\\/g, '/')}` || process.argv[1]?.endsWith('tokens-css.mjs')) {
  const css = render(read());
  writeFileSync(OUTPUT, css, 'utf8');
  const count = css.match(/^\s*--/gm)?.length ?? 0;
  console.log(`src/design/tokens.css: ${count} properties`);
}
